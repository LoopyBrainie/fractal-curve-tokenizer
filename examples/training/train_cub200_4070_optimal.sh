# │                                                                          │
# │   数据集特性:                                                            │
# │     - 细粒度分类: 类间差异小，需要精细局部特征                           │
# │     - 小样本: N < 10K，需要强正则化                                      │
# │     - 高分辨率: 224×224 适合 max_level=4                                 │
# └──────────────────────────────────────────────────────────────────────────┘
#
# ┌──────────────────────────────────────────────────────────────────────────┐
# │ §2. 空间分辨率与 max_level 推导                                          │
# ├──────────────────────────────────────────────────────────────────────────┤
# │   Patch 尺寸公式:                                                        │
# │     patch_size(d) = H / 2^d                                              │
# │                                                                          │
# │   max_level=3 (num_scales=4):                                            │
# │     d=0: 224/1  = 224×224 (全图)                                         │
# │     d=1: 224/2  = 112×112                                                │
# │     d=2: 224/4  = 56×56                                                  │
# │     d=3: 224/8  = 28×28  ← 最小 patch                                    │
# │                                                                          │
# │   max_level=4 (num_scales=5):                                            │
# │     d=0: 224/1  = 224×224 (全图)                                         │
# │     d=1: 224/2  = 112×112                                                │
# │     d=2: 224/4  = 56×56                                                  │
# │     d=3: 224/8  = 28×28                                                  │
# │     d=4: 224/16 = 14×14  ← 最小 patch                                    │
# │                                                                          │
# │   细粒度分类需求分析:                                                    │
# │     - 鸟类区分特征: 喙形、眼纹、羽毛纹理                                 │
# │     - 这些特征尺度: 10-30 像素                                           │
# │     - 14×14 patch 能更好捕获这些局部特征                                 │
# │     ∴ 选择 max_level=4, num_scales=5                                     │
# └──────────────────────────────────────────────────────────────────────────┘
#
# ┌──────────────────────────────────────────────────────────────────────────┐
# │ §3. Token 数量约束推导                                                   │
# ├──────────────────────────────────────────────────────────────────────────┤
# │   候选区域总数 (四叉树结构):                                             │
# │     N_candidates = Σ_{d=0}^{L} 4^d = (4^{L+1} - 1) / 3                   │
# │                                                                          │
# │   max_level=4 时:                                                        │
# │     N_candidates = (4^5 - 1) / 3 = (1024 - 1) / 3 = 341                  │
# │     验证: 1 + 4 + 16 + 64 + 256 = 341 ✓                                  │
# │                                                                          │
# │   K_min 推导 (信息论下界):                                               │
# │     分类所需信息: I = log₂(C) = log₂(200) = 7.64 bits                    │
# │     每 token 信息容量: ~1.5 bits (经验值)                                │
# │     理论下界: K_theory = ⌈7.64 / 1.5⌉ = 6                                │
# │     安全系数 2×: K_min = 2 × 6 = 12                                      │
# │                                                                          │
# │   K_max 推导 (VRAM 约束):                                                │
# │     Attention 矩阵 per sample:                                           │
# │       V_attn = H × K² × 4 bytes (fp32)                                   │
# │                                                                          │
# │     若 K_max = 341 (全部候选):                                           │
# │       V_attn = 8 × 341² × 4 = 3.72 MB/sample                             │
# │       batch=64: V_batch = 238 MB                                         │
# │                                                                          │
# │     若 K_max = 196 (ViT-B/16 标准):                                      │
# │       V_attn = 8 × 196² × 4 = 1.23 MB/sample                             │
# │       batch=64: V_batch = 79 MB                                          │
# │                                                                          │
# │     权衡: K_max=256 平衡精度与 VRAM                                      │
# │       V_attn = 8 × 256² × 4 = 2.1 MB/sample                              │
# │       batch=64: V_batch = 134 MB                                         │
# │     ∴ K_max = 256                                                        │
# └──────────────────────────────────────────────────────────────────────────┘
#
# ┌──────────────────────────────────────────────────────────────────────────┐
# │ §4. 模型容量推导 (Double Descent Theory)                                 │
# ├──────────────────────────────────────────────────────────────────────────┤
# │   Belkin et al. (2019) 插值阈值:                                         │
# │     P_interpolation ≈ N (参数数 ≈ 样本数时发生相变)                      │
# │     过参数化区域: P >> N 时泛化再次改善                                  │
# │                                                                          │
# │   ViT 细粒度分类经验:                                                    │
# │     最优 P/N 比: [500×, 2000×]                                           │
# │     目标: P/N ≈ 1500×                                                    │
# │     ∴ P_target = 1500 × 5994 ≈ 9M                                        │
# │                                                                          │
# │   Transformer 参数公式:                                                  │
# │     P_attn = depth × 4 × dim²        (Q, K, V, O projections)            │
# │     P_ffn  = depth × 3 × dim × mlp_dim   (SwiGLU: gate, up, down)        │
# │     P_total = P_attn + P_ffn + P_embed + P_head                          │
# │                                                                          │
# │   配置验证 (dim=256, depth=8, mlp_dim=4×dim=1024):                       │
# │     P_attn = 8 × 4 × 256² = 2,097,152                                    │
# │     P_ffn  = 8 × 3 × 256 × 1024 = 6,291,456                              │
# │     P_transformer = 8,388,608                                            │
# │     P_embed ≈ 256 × 256 + 256 = 65,792                                   │
# │     P_head = 256 × 200 = 51,200                                          │
# │     P_total ≈ 8.5M                                                       │
# │                                                                          │
# │   验证: P/N = 8.5M / 5994 ≈ 1418× ∈ [500×, 2000×] ✓                      │
# └──────────────────────────────────────────────────────────────────────────┘
#
# ┌──────────────────────────────────────────────────────────────────────────┐
# │ §5. 学习率推导                                                           │
# ├──────────────────────────────────────────────────────────────────────────┤
# │   Linear Scaling Rule (Goyal et al., 2017):                              │
# │     lr = lr_base × (batch_eff / batch_ref)                               │
# │                                                                          │
# │   基准配置:                                                              │
# │     lr_base = 5×10⁻⁴ (AdamW + ViT 标准 @ batch=256)                      │
# │     batch_ref = 256                                                      │
# │                                                                          │
# │   实际配置:                                                              │
# │     batch_size = 64                                                      │
# │     accum_steps = 3                                                      │
# │     batch_eff = 64 × 3 = 192                                             │
# │                                                                          │
# │   基础计算:                                                              │
# │     lr = 5×10⁻⁴ × (192 / 256) = 5×10⁻⁴ × 0.75 = 3.75×10⁻⁴               │
# │                                                                          │
# │   修正因子:                                                              │
# │     α_mixup = 0.85 (Mixup 使梯度噪声增加，需降低 lr)                     │
# │     α_small = 0.85 (小数据集更敏感，进一步降低)                          │
# │                                                                          │
# │   最终计算:                                                              │
# │     lr_final = 3.75×10⁻⁴ × 0.85 × 0.85                                   │
# │              = 3.75×10⁻⁴ × 0.7225                                        │
# │              = 2.71×10⁻⁴ ≈ 2.7×10⁻⁴                                      │
# └──────────────────────────────────────────────────────────────────────────┘
#
# ┌──────────────────────────────────────────────────────────────────────────┐
# │ §6. 正则化强度推导                                                       │
# ├──────────────────────────────────────────────────────────────────────────┤
# │   基准 (Tiny-ImageNet, N=100K):                                          │
# │     weight_decay = 0.1                                                   │
# │     dropout = 0.15                                                       │
# │     drop_path = 0.2                                                      │
# │     label_smoothing = 0.1                                                │
# │                                                                          │
# │   缩放原则: 正则化强度 ∝ 1/√N (偏差-方差权衡)                            │
# │     scale = √(N_ref / N_target) = √(100000 / 5994) = 4.08                │
# │     限制: scale ∈ [1.0, 2.0] 避免过度正则化                              │
# │     ∴ scale = 2.0                                                        │
# │                                                                          │
# │   Weight Decay 计算:                                                     │
# │     wd = 0.1 × scale = 0.1 × 2.0 = 0.20                                  │
# │     但过高 wd 会欠拟合，限制 wd ≤ 0.15                                   │
# │     ∴ weight_decay = 0.15                                                │
# │                                                                          │
# │   Dropout 计算:                                                          │
# │     dp = 0.15 × min(scale, 1.5) = 0.15 × 1.5 = 0.225                     │
# │     限制: dp ≤ 0.25                                                      │
# │     ∴ dropout = 0.22                                                     │
# │                                                                          │
# │   Embedding Dropout:                                                     │
# │     emb_dp = 0.1 × 1.5 = 0.15                                            │
# │     ∴ emb_dropout = 0.15                                                 │
# │                                                                          │
# │   Drop Path (Stochastic Depth):                                          │
# │     公式: drop_path = 0.1 × depth / 6 × scale_factor                     │
# │     scale_factor = min(1.2, scale) = 1.2                                 │
# │     drop_path = 0.1 × 8/6 × 1.2 = 0.16                                   │
# │     ∴ drop_path = 0.16                                                   │
# │                                                                          │
# │   Label Smoothing (细粒度分类):                                          │
# │     公式: ls = 0.1 × (1 + log₁₀(C/100))                                  │
# │     ls = 0.1 × (1 + log₁₀(2)) = 0.1 × 1.301 = 0.13                       │
# │     ∴ label_smoothing = 0.13                                             │
# └──────────────────────────────────────────────────────────────────────────┘
#
# ┌──────────────────────────────────────────────────────────────────────────┐
# │ §7. 数据增强推导 (Mixup/CutMix)                                          │
# ├──────────────────────────────────────────────────────────────────────────┤
# │   细粒度分类约束:                                                        │
# │     - 类间差异微妙 → 过度混合会破坏判别特征                              │
# │     - 局部特征关键 → CutMix 比 Mixup 更有效                              │
# │                                                                          │
# │   Mixup Alpha 推导:                                                      │
# │     标准 ViT: α = 0.8                                                    │
# │     细粒度修正: α_fg = α × 0.5 = 0.4                                     │
# │     小数据集修正: α_final = α_fg × 0.75 = 0.3                            │
# │     ∴ mixup_alpha = 0.3                                                  │
# │                                                                          │
# │   CutMix Alpha 推导:                                                     │
# │     CutMix 保留更多原始像素 → 可用更高 α                                 │
# │     标准: α = 1.0                                                        │
# │     细粒度: α_fg = 1.0 × 0.8 = 0.8                                       │
# │     ∴ cutmix_alpha = 0.8                                                 │
# │                                                                          │
# │   应用概率:                                                              │
# │     小数据集应更保守 → prob = 0.4 (而非标准 0.5)                         │
# │     ∴ mixup_prob = 0.4                                                   │
# └──────────────────────────────────────────────────────────────────────────┘
#
# ┌──────────────────────────────────────────────────────────────────────────┐
# │ §8. Warmup 推导                                                          │
# ├──────────────────────────────────────────────────────────────────────────┤
# │   公式: warmup_epochs = max(5, min(10, epochs × 0.05))                   │
# │   计算: warmup = max(5, min(10, 100 × 0.05))                             │
# │                = max(5, min(10, 5))                                      │
# │                = max(5, 5) = 5                                           │
# │                                                                          │
# │   小数据集修正: 更长 warmup 避免初期震荡                                 │
# │     warmup_adjusted = warmup × 1.4 = 5 × 1.4 = 7                         │
# │   ∴ warmup_epochs = 7                                                    │
