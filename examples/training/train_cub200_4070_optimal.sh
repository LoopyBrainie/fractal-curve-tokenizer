#!/bin/bash
# ============================================================================
# CUB-200-2011 最优训练脚本 - Fractal ViT 细粒度分类
# RTX 4070 Laptop (8GB VRAM) 优化配置
# ============================================================================
#
# 数学形式化分析 (2026-01-15)
# ===========================
#
# [1] 数据集分析
#     ------------------------------------------------------------------
#     N_train = 5,994
#     N_test  = 5,794
#     C       = 200 类
#     图像尺寸 = 224×224×3
#     样本/类 = 30.0 (细粒度分类，每类样本少)
#
#     特点:
#       - 类间差异小 (均为鸟类)
#       - 类内差异大 (姿态、光照变化)
#       - 需要关注局部细节 (喙、羽毛、翅膀纹理)
#
# [2] 模型容量分析 (Double Descent Theory)
#     ------------------------------------------------------------------
#     小数据集需要适当容量，避免过拟合
#
#     候选配置:
#       dim=192, depth= 6: P = 4.40M  (734× N_train)
#       dim=256, depth= 8: P = 8.05M  (1343× N_train) ← 选择
#       dim=320, depth=10: P = 14.06M (2346× N_train)
#       dim=384, depth=12: P = 23.03M (3842× N_train)
#
#     选择 dim=256, depth=8:
#       - 参数量 ~8.05M
#       - P/N ≈ 1343× (需要强正则化)
#       - 计算效率高，适合快速迭代
#
# [3] Token 约束 (信息论推导)
#     ------------------------------------------------------------------
#     K_min:
#       log2(200) = 7.64 bits
#       K_min_theory = ceil(7.64 / 1.5) = 6
#       K_min = 2 × 6 = 12 (带冗余)
#
#     K_max:
#       最细粒度 patches = (224/4)² = 3136
#       K_max = 3136 / 4 = 784 → 限制到 256 (计算效率)
#
#     num_scales = 4 (max_depth = 3)
#       尺度: 4×4, 8×8, 16×16, 32×32
#
# [4] 学习率计算 (Linear Scaling Rule)
#     ------------------------------------------------------------------
#     lr_base = 5e-4 @ B=256
#     Linear Scaling: 5e-4 × (192/256) = 3.75e-4
#     小数据集修正 (×0.7): 3.75e-4 × 0.7 = 2.6e-4
#
# [5] 正则化参数 (小数据集强正则化)
#     ------------------------------------------------------------------
#     Weight Decay:
#       wd = 0.05 × sqrt(P/N) = 0.05 × sqrt(1343) ≈ 1.83
#       裁剪后 = 0.20
#
#     Drop Path:
#       0.1 × (8/6) + 0.05 = 0.18
#
#     Dropout = 0.20, Emb Dropout = 0.15
#     Label Smoothing = 0.15 (细粒度分类)
#
# [6] VRAM 预算验证
#     ------------------------------------------------------------------
#     模型参数:   16.1 MB (FP16)
#     激活内存:   38.5 MB (with gradient checkpoint)
#     输入缓存:  115.6 MB
#     梯度内存:   16.1 MB
#     优化器:     64.4 MB
#     CUDA开销: ~300 MB
#     --------------------------------
#     总计: ~551 MB / 7500 MB ✓
#
# [7] 训练动态
#     ------------------------------------------------------------------
#     steps_per_epoch = ceil(5994/192) = 32
#     total_steps = 32 × 100 = 3,200
#     warmup = 5 epochs = 160 steps
#     预计训练时间: ~27 分钟
#
# ============================================================================

uv run python examples/training/train_fractal_vit.py \
  --dataset cub200 \
  --epochs 100 \
  \
  # ======================================================================== #
  # 模型架构 (~8M 参数, Double Descent 优化)                                 #
  #   dim=256, depth=8 适配小数据集 (N=5994)                                 #
  #   P/N ≈ 1343× → 需要强正则化                                            #
  # ======================================================================== #
  --dim 256 \
  --depth 8 \
  --heads 8 \
  --dim-head 32 \
  --max-level 3 \
  --pool cls \
  --ffn-type swiglu_level \
  \
  # ======================================================================== #
  # Scheme E: GumbelTopKSplitter 配置                                        #
  #   K_min = 12: 2 × ceil(log2(200)/1.5)                                    #
  #   K_max = 256: (224/4)²/4 限制到 256                                     #
  #   num_scales = 4: 4×4, 8×8, 16×16, 32×32                                 #
  # ======================================================================== #
  --tokenizer-type streaming_v3 \
  --num-scales 4 \
  --K-min 12 \
  --K-max 256 \
  \
  # ======================================================================== #
  # 训练配置                                                                 #
  #   batch_size = 192: 最大可用 (with gradient checkpoint)                 #
  #   lr = 2.6e-4: Linear Scaling + 小数据集修正                            #
  #   warmup = 5 epochs                                                      #
  # ======================================================================== #
  --batch-size 192 \
  --lr 2.6e-4 \
  --warmup-epochs 5 \
  --lr-scheduler cosine \
  --min-lr 1e-6 \
  \
  # ======================================================================== #
  # 正则化 (小数据集强正则化)                                                #
  #   weight_decay = 0.20: sqrt(P/N) scaling                                #
  #   dropout = 0.20: 较高以防过拟合                                        #
  #   drop_path = 0.18: Stochastic Depth                                    #
  #   label_smoothing = 0.15: 细粒度分类                                    #
  # ======================================================================== #
  --weight-decay 0.20 \
  --dropout 0.20 \
  --emb-dropout 0.15 \
  --drop-path 0.18 \
  --label-smoothing 0.15 \
  \
  # ======================================================================== #
  # 数据增强 (细粒度分类特殊配置)                                            #
  #   mixup_alpha = 0.4: 较弱，保留判别特征                                 #
  #   cutmix_alpha = 0.6: 较弱                                              #
  # ======================================================================== #
  --mixup-alpha 0.4 \
  --cutmix-alpha 0.6 \
  --mix-prob 0.5 \
  \
  # ======================================================================== #
  # 硬件优化 (RTX 4070 Laptop)                                              #
  #   --compile: torch.compile 加速                                         #
  #   --channels-last: 内存布局优化                                         #
  #   --gradient-checkpointing: 节省 VRAM                                   #
  #   --amp: FP16 混合精度                                                  #
  # ======================================================================== #
  --compile \
  --channels-last \
  --gradient-checkpointing \
  --amp \
  \
  # ======================================================================== #
  # 日志与检查点                                                             #
  # ======================================================================== #
  --log-interval 10 \
  --save-interval 20 
